// REQ-UI-003 — writes src/app/theme.css from the @openmap/ui tokens (Tailwind @theme block, --om-* variables,
// direction blocks and keyframes). Runs in predev/prebuild; the output is generated, never committed.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { stylesheet, themeCss } from '@openmap/ui';

const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, '..', 'src', 'app', 'theme.css');
const banner = '/* Generated by scripts/gen-theme.ts from @openmap/ui. Do not edit; regenerated on every dev/build. */\n\n';

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, banner + themeCss() + '\n' + stylesheet());
console.log('theme: wrote ' + target);
