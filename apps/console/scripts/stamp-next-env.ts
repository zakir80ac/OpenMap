// REQ-UI-003 — Next.js regenerates next-env.d.ts on every build without a requirement header; tools/guard requires
// one in every apps/ source file, so this postbuild step prepends it. Next compares file content, so the stamp
// is re-applied after each build rather than fighting the generator.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const file = join(here, '..', 'next-env.d.ts');
const stamp = '// REQ-UI-003 — generated by Next.js; header added by scripts/stamp-next-env.ts for tools/guard.';

if (existsSync(file)) {
  const current = readFileSync(file, 'utf8');
  if (!current.startsWith(stamp)) writeFileSync(file, stamp + '\n' + current);
}
